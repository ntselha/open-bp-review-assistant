"""8. LLM staff summary (disposable prompt calling a versioned LLM).

The model is the atomic part: Anthropic Claude, pinned by model ID in
config.yaml (llm.model) and cited through its model card. The prompt in
prompts/staff_summary_prompt.txt is my own, so this step is disposable.

Input:  results_json str (group counts and per-patient numbers),
        llm settings dict {enabled, model, max_tokens},
        prompt_template str containing "{results_json}",
        client (optional; anything with .messages.create(), used by tests)
Output: (summary text str, note str), or (None, reason str) when the step
        is skipped: disabled in config, ANTHROPIC_API_KEY not set, or the
        anthropic package not installed. The workflow then uses the template
        summary, so it always runs without a key.
"""

from __future__ import annotations

import os


def llm_staff_summary(results_json: str, llm: dict, prompt_template: str,
                      client=None) -> tuple[str | None, str]:
    if not llm.get("enabled", False):
        return None, "LLM disabled in config.yaml"
    if client is None:
        if not os.environ.get("ANTHROPIC_API_KEY"):
            return None, "ANTHROPIC_API_KEY not set"
        try:
            import anthropic  # optional; see requirements-llm.txt
        except ImportError:
            return None, "anthropic package not installed"
        client = anthropic.Anthropic()
    response = client.messages.create(
        model=llm["model"],
        max_tokens=llm["max_tokens"],
        messages=[{"role": "user",
                   "content": prompt_template.replace("{results_json}", results_json)}],
    )
    text = "".join(b.text for b in response.content if getattr(b, "type", "") == "text")
    return text.strip(), f"generated by {llm['model']}"
