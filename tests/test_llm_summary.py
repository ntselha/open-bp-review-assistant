"""Unit tests for 8. LLM staff summary (openbp/llm_summary.py).

No network calls: a fake client stands in for the Anthropic API, so these
run free in GitHub Actions. They check the wiring (model ID from config,
prompt filled with the JSON, text extracted) and the skip paths.
"""

from types import SimpleNamespace

import pytest

from conftest import ROOT
from openbp.llm_summary import llm_staff_summary

LLM = {"enabled": True, "model": "claude-haiku-5-5", "max_tokens": 400}
PROMPT = (ROOT / "prompts" / "staff_summary_prompt.txt").read_text(encoding="utf-8")


class FakeClient:
    def __init__(self, reply):
        self.calls = []
        self.messages = SimpleNamespace(create=self._create)
        self._reply = reply

    def _create(self, **kwargs):
        self.calls.append(kwargs)
        return SimpleNamespace(content=[SimpleNamespace(type="text", text=self._reply)])


def test_calls_pinned_model_with_filled_prompt():
    client = FakeClient("  Two patients need outreach.  ")
    text, note = llm_staff_summary('{"n": 2}', LLM, PROMPT, client=client)
    assert text == "Two patients need outreach."
    assert note == "generated by claude-haiku-5-5"
    call = client.calls[0]
    assert call["model"] == "claude-haiku-5-5" and call["max_tokens"] == 400
    content = call["messages"][0]["content"]
    assert '{"n": 2}' in content and "{results_json}" not in content


def test_prompt_forbids_clinical_interpretation():
    assert "Do not interpret results clinically" in PROMPT
    assert "Use only numbers that appear in the JSON" in PROMPT


def test_skipped_when_disabled():
    text, note = llm_staff_summary("{}", dict(LLM, enabled=False), PROMPT,
                                   client=FakeClient("x"))
    assert text is None and "disabled" in note


def test_skipped_without_api_key(monkeypatch):
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    text, note = llm_staff_summary("{}", LLM, PROMPT)
    assert text is None and note == "ANTHROPIC_API_KEY not set"


def test_skipped_when_package_missing(monkeypatch):
    import builtins
    real_import = builtins.__import__

    def no_anthropic(name, *args, **kwargs):
        if name == "anthropic":
            raise ImportError
        return real_import(name, *args, **kwargs)

    monkeypatch.setenv("ANTHROPIC_API_KEY", "test-key-not-real")
    monkeypatch.setattr(builtins, "__import__", no_anthropic)
    text, note = llm_staff_summary("{}", LLM, PROMPT)
    assert text is None and note == "anthropic package not installed"
